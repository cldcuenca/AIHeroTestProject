test('dirty Cancel and Escape require discard confirmation; Keep Editing retains drafts and native warnings exist only while dirty', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Task title' }).fill('Saved title');
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  const trigger = page.getByRole('button', { name: 'Edit Saved title', exact: true });
  await trigger.click();
  const editor = page.getByRole('dialog', { name: 'Edit task', exact: true });
  const title = editor.getByRole('textbox', { name: 'Title', exact: true });
  const requestsWarning = () => page.evaluate(() => {
    const event = new Event('beforeunload', { cancelable: true });
    window.dispatchEvent(event);
    return event.defaultPrevented;
  });
  expect(await requestsWarning()).toBe(false);
  await page.keyboard.press('Shift+Tab');
  await expect(editor.getByRole('button', { name: 'Save', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(title).toBeFocused();
  await title.fill('Unsaved title');
  await editor.getByRole('textbox', { name: 'Notes', exact: true }).fill('Unsaved\nnotes');
  expect(await requestsWarning()).toBe(true);
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  const discard = page.getByRole('dialog', { name: 'Discard unsaved changes?', exact: true });
  const keep = discard.getByRole('button', { name: 'Keep Editing', exact: true });
  await expect(keep).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(discard.getByRole('button', { name: 'Discard changes', exact: true })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(keep).toBeFocused();
  await keep.press('Enter');
  await expect(title).toHaveValue('Unsaved title');
  await expect(editor.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Unsaved\nnotes');
  await expect(editor.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(discard).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(title).toHaveValue('Unsaved title');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await discard.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect(editor).not.toBeVisible();
  await expect(trigger).toBeFocused();
  expect(await requestsWarning()).toBe(false);
  await trigger.click();
  await expect(title).toHaveValue('Saved title');
  await expect(editor.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('');
  await title.fill('Temporary');
  await title.fill('Saved title');
  expect(await requestsWarning()).toBe(false);
  await page.keyboard.press('Escape');
  await expect(editor).not.toBeVisible();
  await expect(discard).not.toBeVisible();
  await page.reload();
  await expect(trigger).toBeVisible();
});

